// The public payment page of an invoice (PRO-187), opened by the QR code on the PDF: /payer/<token>.
// It shows the seller, the invoice number and what is left to pay *now*, and a PI-SPI QR code to pay it:
//  - through Paygate: Billio's Worker asks Paygate for a collection; the payment is recorded on the invoice by
//    itself (Paygate's webhook), and this page sees the balance drop;
//  - on the business's own alias: the QR carries the invoice number as its reference, the business matches it.
// No sign-in, nothing editable, nothing but what the token's link shows.
import { useCallback, useEffect, useRef, useState } from 'react';
import { useParams } from 'react-router-dom';
import { generateQrCodeSvg } from '@pi-spi/qrcode';
import BillioMark from '@/components/BillioMark';
import { aliasQrFields } from '@/lib/online-payments';
import { fmt } from '@/data';

interface PageInfo {
  seller: string; invoice: string; issuedAt: string; total: number; balance: number; currency: 'XOF';
  state: 'open' | 'paid' | 'closed'; mode: 'off' | 'alias' | 'paygate'; alias?: string | null; country?: string | null;
}
interface QrFields { alias: string; countryCode: string; qrType: 'DYNAMIC' | 'STATIC'; referenceLabel: string; amount: number }
interface Collection { amount: number; qr: QrFields; expiresAt: string | null }

const POLL_MS = 5000;
const POLL_FOR_MS = 20 * 60_000;

/**
 * The PI-SPI QR code as the BCEAO's own SDK draws it: the EMV payload, with the PI-SPI logo in the centre.
 * The SVG comes from @pi-spi/qrcode, built from the payment's fields only (no text of ours is inserted as markup).
 */
function PispiQr({ fields }: { fields: QrFields }) {
  const [svg, setSvg] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    let cancelled = false;
    setSvg(null); setFailed(false);
    generateQrCodeSvg(fields, { size: 520 })
      .then(s => { if (!cancelled) setSvg(s); })
      .catch(err => { console.error('[PispiQr]', err); if (!cancelled) setFailed(true); });
    return () => { cancelled = true; };
  }, [fields]);
  if (failed) return <div className="paypg-error" role="alert">Le QR code n’a pas pu être affiché. Rechargez la page.</div>;
  // the SVG is generated by the BCEAO's SDK from the payment's fields: no text of ours becomes markup
  return (
    <div className="paypg-qr" role="img" aria-label={`QR code PI-SPI de ${fmt(fields.amount)} F CFA`} aria-busy={!svg}
      dangerouslySetInnerHTML={svg ? { __html: svg } : undefined} />
  );
}

const Shell = ({ children }: { children: React.ReactNode }) => (
  <main className="auth-root">
    <div className="auth-card" style={{ maxWidth: 440 }}>
      <section className="form-panel" style={{ borderRadius: 'inherit' }}>
        <div className="fp-inner">{children}</div>
      </section>
    </div>
  </main>
);

export default function PayPage() {
  const { token = '' } = useParams<{ token: string }>();
  const [info, setInfo] = useState<PageInfo | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [collection, setCollection] = useState<Collection | null>(null);
  const [busy, setBusy] = useState(false);
  const [paid, setPaid] = useState(false);
  const startBalance = useRef<number | null>(null);

  const load = useCallback(async (): Promise<PageInfo | null> => {
    const res = await fetch(`/api/pay/${encodeURIComponent(token)}`, { cache: 'no-store' });
    const body = await res.json().catch(() => null) as (PageInfo & { message?: string }) | null;
    if (!res.ok || !body) { setError(body?.message ?? 'Ce lien de paiement n’est pas disponible.'); return null; }
    setInfo(body);
    return body;
  }, [token]);

  useEffect(() => { load().catch(() => setError('Service momentanément indisponible. Réessayez dans quelques minutes.')); }, [load]);

  // While a Paygate QR code is shown: watch the balance, so the client sees the payment arrive
  useEffect(() => {
    if (!collection || paid) return;
    const until = Date.now() + POLL_FOR_MS;
    const t = window.setInterval(async () => {
      if (Date.now() > until) { window.clearInterval(t); return; }
      const now = await load().catch(() => null);
      if (now && (now.state === 'paid' || (startBalance.current !== null && now.balance < startBalance.current))) { setPaid(true); window.clearInterval(t); }
    }, POLL_MS);
    return () => window.clearInterval(t);
  }, [collection, paid, load]);

  async function pay() {
    setBusy(true); setError(null);
    try {
      const res = await fetch(`/api/pay/${encodeURIComponent(token)}/collect`, { method: 'POST' });
      const body = await res.json().catch(() => null) as (Collection & { message?: string }) | null;
      if (!res.ok || !body?.qr) { setError(body?.message ?? 'Paiement impossible pour le moment.'); return; }
      startBalance.current = info?.balance ?? null;
      setCollection(body);
    } catch {
      setError('Service momentanément indisponible. Réessayez dans quelques minutes.');
    } finally {
      setBusy(false);
    }
  }

  if (error && !info) return <Shell><div className="fp-eyebrow" style={{ color: 'var(--color-danger)' }}>Lien indisponible</div><h1 className="fp-title">Paiement</h1><div className="fp-sub">{error}</div></Shell>;
  if (!info) return <Shell><div className="fp-sub" aria-busy="true">Chargement…</div></Shell>;

  const head = (
    <>
      <div style={{ marginBottom: 18 }}><BillioMark /></div>
      <div className="fp-eyebrow">{info.seller}</div>
      <h1 className="fp-title">Facture {info.invoice}</h1>
    </>
  );

  if (paid || info.state === 'paid') return (
    <Shell>{head}
      <div className="paypg-done" role="status">{paid ? 'Paiement reçu. Merci !' : 'Cette facture est réglée.'}</div>
      {paid && info.balance > 0 && <div className="fp-sub">Reste à payer : {fmt(info.balance)} F CFA.</div>}
    </Shell>
  );
  if (info.state === 'closed' || info.mode === 'off') return (
    <Shell>{head}<div className="fp-sub">{info.state === 'closed' ? 'Cette facture n’attend pas de paiement.' : 'Paiement en ligne indisponible. Contactez l’entreprise.'}</div></Shell>
  );

  const amountLine = (
    <div className="paypg-amount"><span>Reste à payer</span><strong>{fmt(info.balance)} F CFA</strong>{info.balance < info.total && <small>sur {fmt(info.total)} F CFA</small>}</div>
  );

  if (info.mode === 'alias' && info.alias) {
    const fields = aliasQrFields(info.alias, info.country ?? 'BF', info.invoice, info.balance);
    return (
      <Shell>{head}{amountLine}
        <PispiQr fields={fields} />
        <ol className="paypg-steps">
          <li>Ouvrez votre application bancaire ou de mobile money.</li>
          <li>Scannez ce QR code et validez {fmt(info.balance)} F CFA.</li>
        </ol>
        <dl className="paypg-kv"><dt>Bénéficiaire</dt><dd>{info.seller}</dd><dt>Référence</dt><dd>{fields.referenceLabel}</dd></dl>
        
      </Shell>
    );
  }

  return (
    <Shell>{head}{amountLine}
      {!collection ? (
        <>
          <div className="fp-sub">Payez par PI-SPI depuis votre application bancaire ou de mobile money.</div>
          {error && <div className="paypg-error" role="alert">{error}</div>}
          <button className="submit-btn" style={{ marginTop: 20 }} onClick={pay} disabled={busy || info.balance <= 0}>
            {busy ? 'Préparation…' : `Payer ${fmt(info.balance)} F CFA`}
          </button>
        </>
      ) : (
        <>
          <PispiQr fields={collection.qr} />
          <ol className="paypg-steps">
            <li>Ouvrez votre application bancaire ou de mobile money.</li>
            <li>Scannez ce QR code et validez <strong>{fmt(collection.amount)} F CFA</strong>.</li>
          </ol>
          {collection.expiresAt && <div className="fp-sub">Valable jusqu’à {new Date(collection.expiresAt).toLocaleTimeString('fr-FR', { hour: '2-digit', minute: '2-digit' })}.</div>}
          <div className="paypg-wait" role="status" aria-live="polite">En attente de votre paiement…</div>
        </>
      )}
    </Shell>
  );
}
